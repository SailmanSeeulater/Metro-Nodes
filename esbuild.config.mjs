import esbuild from "esbuild";
import { builtinModules } from "node:module";

const mode = process.argv[2] ?? "dev";
const prod = mode === "production";

const banner = "/* Metro Nodes — generated by esbuild. Source: src/ */";

if (mode === "harness") {
	// Standalone browser page that renders the metro view without Obsidian.
	await esbuild.build({
		entryPoints: ["harness/main.ts"],
		bundle: true,
		format: "iife",
		target: "es2020",
		outfile: "harness/dist/harness.js",
		sourcemap: "inline",
		logLevel: "info",
	});
} else {
	const ctx = await esbuild.context({
		banner: { js: banner },
		entryPoints: ["src/main.ts"],
		bundle: true,
		external: [
			"obsidian",
			"electron",
			"@codemirror/*",
			"@lezer/*",
			...builtinModules,
		],
		format: "cjs",
		target: "es2020",
		logLevel: "info",
		sourcemap: prod ? false : "inline",
		treeShaking: true,
		outfile: "main.js",
		minify: prod,
	});
	if (prod) {
		await ctx.rebuild();
		process.exit(0);
	} else {
		await ctx.watch();
	}
}
